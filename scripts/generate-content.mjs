function depthOf(id) {
  return id.split('-').length
}

function inferDifficulty(node) {
  const veryHard = /KMP|Next|AVL|B 树|B\+|关键路径|银行家|页面置换|段页式|Cache 基本|IEEE 754|海明|CRC|流水线|微指令|数据通路|子网|CIDR|TCP 拥塞|GBN|SR 协议|Dijkstra|Floyd|快速排序|堆排序|布斯|除法/
  const hard = /复杂度|递归|非递归|哈夫曼|最小生成树|哈希|ASL|调度算法|信号量|经典同步|死锁|动态分区|分页|分段|磁盘调度|DMA|中断|寻址|浮点|补码|多模块|仲裁|奈奎斯特|香农|CSMA|路由|IPv4|TCP|DNS/

  if (veryHard.test(node.name)) return 5
  if (hard.test(node.name)) return 4
  if (depthOf(node.id) >= 4) return 3
  if (depthOf(node.id) === 3) return 2
  return 1
}

