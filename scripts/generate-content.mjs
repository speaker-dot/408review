async function main() {
  const byId = new Map()
  for (const node of rows) {
    if (!/^((DS|CS|OS|NET)-\d{2})(-\d{2})?(-\d{3})?$/.test(node.id)) {
      throw new Error(`非法节点 ID：${node.id}`)
    }
    if (byId.has(node.id)) throw new Error(`重复节点 ID：${node.id}`)
    byId.set(node.id, node)
  }

  for (const node of rows) {
    if (node.parentId !== node.category && !byId.has(node.parentId)) {
      throw new Error(`${node.id} 的父节点不存在：${node.parentId}`)
    }
  }

  const childrenByParent = new Map()
  for (const node of rows) {
    const children = childrenByParent.get(node.parentId) ?? []
    children.push(node)
    childrenByParent.set(node.parentId, children)
  }

  for (const meta of Object.values(subjectMeta)) {
    await mkdir(path.join(contentRoot, meta.folder), { recursive: true })
  }

  for (const node of rows) {
    const children = childrenByParent.get(node.id) ?? []
    const profile = resolveProfile(node, children)
    const record = {
      id: node.id,
      name: node.name,
      category: node.category,
      parentId: node.parentId,
      difficulty: inferDifficulty(node),
      summary: compactSummary(node, profile),
      details: buildDetails(node, profile, children),
      traps: profile.traps,
      quizzes: [buildChoice(node, profile), buildAnalysis(node, profile)],
    }

    const target = path.join(
      contentRoot,
      subjectMeta[node.category].folder,
      `${node.id}.json`,
    )
    await writeFile(target, `${JSON.stringify(record, null, 2)}\n`, 'utf8')
  }

  const roots = Object.entries(subjectMeta).map(([id, meta]) => ({
    id,
    name: meta.name,
    symbolSize: 68,
  }))
  const nodes = rows.map((node) => ({
    id: node.id,
    name: node.name,
    parentId: node.parentId,
    symbolSize: depthOf(node.id) === 2 ? 54 : depthOf(node.id) === 3 ? 40 : 28,
  }))
  const links = rows.map((node) => ({ source: node.parentId, target: node.id }))
  const index = { nodes: [...roots, ...nodes], links }

  await writeFile(
    path.join(contentRoot, 'index.json'),
    `${JSON.stringify(index, null, 2)}\n`,
    'utf8',
  )

  console.log(`Generated ${rows.length} knowledge nodes and ${links.length} links.`)
}

await main()
